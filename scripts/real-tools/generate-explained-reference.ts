// Rebuild the exact executable examples shown by the form reference. The unit checks compare
// this generated output byte for byte; check.mjs executes every entry under GNU/QEMU.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ARITHMETIC_GUIDES } from "../../content/reference-guides/arithmetic.ts";
import { LOGIC_GUIDES } from "../../content/reference-guides/logic.ts";
import { CONTROL_GUIDES } from "../../content/reference-guides/control.ts";
import { MEMORY_GUIDES } from "../../content/reference-guides/memory.ts";
import {
  buildReferenceExample,
  computeReferenceExample,
} from "../../content/reference-guides/model.ts";
import type { ReferenceGuideFamily } from "../../content/reference-guides/types.ts";

export function explainedReferenceCorpus(families: readonly ReferenceGuideFamily[]) {
  const guides = families
    .flatMap((family) => Object.entries(family))
    .sort(([a], [b]) => a.localeCompare(b));
  const examples = guides.flatMap(([mnemonic, forms]) =>
    forms.flatMap((form) => form.examples.map((example) => ({ mnemonic, form, example }))),
  );
  const names = new Set<string>();
  const compare = new Map<string, number>();
  const programs = examples.map(({ mnemonic, form, example }, index) => {
    if (names.has(example.id)) throw new Error(`Duplicate explained example id: ${example.id}`);
    names.add(example.id);
    computeReferenceExample(example);
    const built = buildReferenceExample(example, `explained_reference_${index}`);
    for (const watch of example.watch) {
      if (watch.kind !== "memory") continue;
      const label = [...built.labelNames].find(([, original]) => original === watch.symbol)?.[0];
      if (!label) throw new Error(`Missing watched native label ${watch.symbol} in ${example.id}`);
      compare.set(label, Math.max(compare.get(label) ?? 0, watch.bytes));
    }
    return `// Example ${index}: ${mnemonic} / ${form.id} / ${example.id}\n${built.source}`;
  });
  const mistakes = [
    ...new Set(
      guides.flatMap(([, forms]) =>
        forms.flatMap((form) => (form.mistakes ?? []).map((mistake) => mistake.source)),
      ),
    ),
  ];
  if (mistakes.some((source) => source.split("\n").filter((line) => line.trim()).length !== 1)) {
    throw new Error("Native counterexamples must each contain one instruction");
  }
  return {
    mistakesSource: `// each line alone\n// Copyright © 2026 Christopher Snow\n// Generated from the rejected operand examples in the form reference.\n${mistakes.join("\n")}\n`,
    source: `// Copyright © 2026 Christopher Snow\n// Generated by scripts/real-tools/generate-explained-reference.ts.\n// Each displayed instruction uses its own independent prepared context.\n\n${programs.join("\n")}\n`,
    spec: {
      entry: "explained_reference_0",
      calls: examples.map((_, index) => ({
        entry: `explained_reference_${index}`,
        args: [],
        flags: "0000",
      })),
      compare: [...compare].map(([label, length]) => ({ label, length })),
    },
  };
}

export const EXPLAINED_GUIDE_FAMILIES = [
  ARITHMETIC_GUIDES,
  LOGIC_GUIDES,
  CONTROL_GUIDES,
  MEMORY_GUIDES,
] as const;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const corpus = explainedReferenceCorpus(EXPLAINED_GUIDE_FAMILIES);
  writeFileSync(new URL("./corpus/explained-reference-examples.s", import.meta.url), corpus.source);
  writeFileSync(
    new URL("./corpus/explained-reference-examples.json", import.meta.url),
    `${JSON.stringify(corpus.spec, null, 2)}\n`,
  );
  writeFileSync(
    new URL("./lines/explained-reference-mistakes.s", import.meta.url),
    corpus.mistakesSource,
  );
  process.stdout.write(`Generated ${corpus.spec.calls.length} independent explained examples.\n`);
}
